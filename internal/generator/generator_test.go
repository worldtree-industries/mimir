// TestGoldenCases generates Go from each testdata/<case>/config.json, compares
// it to the checked-in testdata/<case>/config_gen.go, and builds and tests that
// case's package, so generated code must compile and behave. Set
// UPDATE_GOLDEN=1 to rewrite the golden files.
func TestGoldenCases(t *testing.T) {
	cases, err := filepath.Glob("testdata/*/config.json")
	if err != nil || len(cases) == 0 {
		t.Fatalf("no golden cases found: %v", err)
	}

	for _, configPath := range cases {
		dir := filepath.Dir(configPath)
		t.Run(filepath.Base(dir), func(t *testing.T) {
			goldenPath := filepath.Join(dir, "config_gen.go")

			got := generate(t, configPath, filepath.Base(dir))
			if os.Getenv("UPDATE_GOLDEN") != "" {
				writeFile(t, goldenPath, got)
			}

			if want := readFile(t, goldenPath); string(got) != string(want) {
				t.Errorf("generated code differs from %s (rerun with UPDATE_GOLDEN=1 to accept)", goldenPath)
			}

			out, testErr := exec.CommandContext(t.Context(), "go", "test", "./"+dir).CombinedOutput()
			if testErr != nil {
				t.Errorf("go test %s: %v\n%s", dir, testErr, out)
			}
		})
	}
}

const modulePath = "github.com/worldtree-industries/mimir"

func generate(t *testing.T, configPath, packageName string) []byte {
	t.Helper()

	importPath := modulePath + "/internal/generator/testdata/" + packageName

	got, err := generator.Generate(readFile(t, configPath), packageName, importPath)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}

	return got
}

func readFile(t *testing.T, path string) []byte {
	t.Helper()

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	return data
}

func writeFile(t *testing.T, path string, data []byte) {
	t.Helper()

	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestDuplicateItemNamesAreRejected(t *testing.T) {
	input := []byte(`{"type_name":"DupConfig","items":[
		{"name":"a","description":"","type":"int","value":"1"},
		{"name":"b","description":"","type":"int","value":"1"},
		{"name":"a","description":"","type":"string","value":"x"}]}`)

	got, err := generator.Generate(input, "dup", "example.com/dup")
	if err == nil {
		t.Fatal("expected an error for duplicate Item names")
	}
	if !strings.Contains(err.Error(), `"a"`) {
		t.Errorf("error should name the Item: %v", err)
	}
	if got != nil {
		t.Errorf("no output should be produced, got %d bytes", len(got))
	}
}

// The generated-file header must not become the package doc: Layers keep
// theirs in doc.go, and a second one fails godoclint.
func TestHeaderIsNotThePackageDoc(t *testing.T) {
	input := []byte(`{"type_name":"HeaderConfig","items":[{"name":"a","description":"","type":"int","value":"1"}]}`)

	got, err := generator.Generate(input, "header", "example.com/header")
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}

	const header = "// Code generated by mimir-generate; DO NOT EDIT."
	if first, _, _ := strings.Cut(string(got), "\n"); first != header {
		t.Errorf("first line = %q, want %q", first, header)
	}

	file, err := parser.ParseFile(token.NewFileSet(), "config_gen.go", got, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse generated code: %v", err)
	}
	if file.Doc != nil {
		t.Errorf("generated code has a package doc: %q", file.Doc.Text())
	}
}

// Getter and setter names spell initialisms in one case, as Go naming and
// lint expect of the hand-written code that implements or fakes a Config.
func TestAccessorNamesSpellInitialismsInOneCase(t *testing.T) {
	cases := []struct{ item, getter, setter string }{
		{"opnsense_url", "GetOpnsenseURL", "setOpnsenseURL"},
		{"victorialogs_urls", "GetVictorialogsURLs", "setVictorialogsURLs"},
		{"user_ids", "GetUserIDs", "setUserIDs"},
		{"api_key", "GetAPIKey", "setAPIKey"},
		{"db_url", "GetDBURL", "setDBURL"},
		{"sha256_sum", "GetSha256Sum", "setSha256Sum"},
		{"foo", "GetFoo", "setFoo"},
		{"s_arr", "GetSArr", "setSArr"},
	}

	items := make([]string, 0, len(cases))
	for _, c := range cases {
		items = append(items, `{"name":"`+c.item+`","description":"","type":"string","value":""}`)
	}
	input := []byte(`{"type_name":"NamesConfig","items":[` + strings.Join(items, ",") + `]}`)

	got, err := generator.Generate(input, "names", "example.com/names")
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	methods := methodNames(t, got)

	for _, c := range cases {
		for _, want := range []string{c.getter, c.setter} {
			if !methods[want] {
				t.Errorf("Item %q: no method %s", c.item, want)
			}
		}
	}
}

func methodNames(t *testing.T, src []byte) map[string]bool {
	t.Helper()

	file, err := parser.ParseFile(token.NewFileSet(), "config_gen.go", src, 0)
	if err != nil {
		t.Fatalf("parse generated code: %v", err)
	}

	names := make(map[string]bool)
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv != nil {
			names[fn.Name.Name] = true
		}
	}

	return names
}

func TestOldNamespaceKeyStillNamesTheType(t *testing.T) {
	items := `"items":[{"name":"a","description":"","type":"int","value":"1"}]`
	current, err := generator.Generate([]byte(`{"type_name":"KeyConfig",`+items+`}`), "key", "example.com/key")
	if err != nil {
		t.Fatalf("Generate with type_name: %v", err)
	}
	old, err := generator.Generate([]byte(`{"namespace":"KeyConfig",`+items+`}`), "key", "example.com/key")
	if err != nil {
		t.Fatalf("Generate with the old namespace key: %v", err)
	}
	if !bytes.Equal(old, current) {
		t.Errorf("the old namespace key generated different code than type_name:\n%s", old)
	}
}
